class PassengerPreferences {
  final String ambiance;
  final bool music;
  final bool perfume;
  final bool temperature;
  final bool wifi;
  final bool smokeFree;
  final bool pets;

  PassengerPreferences({
    required this.ambiance,
    required this.music,
    required this.perfume,
    required this.temperature,
    required this.wifi,
    required this.smokeFree,
    required this.pets,
  });
}
